def main():
    DATA.mkdir(exist_ok=True)
    rows = []
    for label, groups in ((1, ATTACKS), (0, HARMLESS)):
        for kind, texts in groups.items():
            assert len(set(texts)) == len(texts), f"duplicate in {kind}"
            for i, text in enumerate(texts):
                rows.append({"text": text, "label": label, "set": "german", "kind": kind,
                             "lang": "de", "split": "dev" if i % 2 == 0 else "test"})
    with open(DATA / "german.jsonl", "w", encoding="utf-8") as out:
        for row in rows:
            out.write(json.dumps(row, ensure_ascii=False) + "\n")
    attacks = sum(r["label"] for r in rows)
    print(f"german: {attacks} attacks, {len(rows) - attacks} harmless")


if __name__ == "__main__":
    main()
